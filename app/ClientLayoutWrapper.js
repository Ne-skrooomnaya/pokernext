'use client';

import React, { useEffect } from 'react';
import useTelegram from '@/hooks/useTelegram'; // Убедитесь, что путь к хуку правильный
// import { useRouter } from 'next/navigation'; // Пока не будем использовать router здесь, иначе может вызвать проблемы с SSR

function ClientLayoutWrapper({ children }) {
  const { tg, user } = useTelegram(); // Вызываем хук здесь

  // --- Важно: Обработка, если SDK не доступен ---
  // Если `tg` остается `null` после попытки инициализации,
  // это значит, что приложение либо не запущено в Telegram Web App,
  // либо произошла ошибка.
  // В этом случае, `children` (ваше приложение) не должно рендериться,
  // или должно рендериться сообщение об ошибке.

  // Если `tg` все еще `null` после инициализации (даже после useEffect),
  // это значит, что SDK либо не доступен, либо произошла ошибка.
  // В таких случаях, дальнейшая логика (авторизация, рендеринг защищенных страниц)
  // не имеет смысла.

  // --- Здесь нет необходимости рендерить что-то специфичное,
  // --- главное, чтобы `tg` и `user` были доступны (или `null` явно)
  // --- для компонентов-потомков.

  // Оставим просто рендеринг children.
  // Все проверки будут внутри компонентов, которые используют tg/user (например, app/page.js)
  // или в middleware.
  return <>{children}</>;
}

export default ClientLayoutWrapper;
